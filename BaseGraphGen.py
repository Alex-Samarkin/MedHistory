def N(i, label, kind, start, end, region, note=""):
    NODES[i] = dict(
        **{"": i}, ID=i, Label=label, Kind=kind, Start=start, End=end,
        Region=region, Note=note,
        Size={"paradigm": 42, "concept": 30, "discovery": 28, "person": 22,
              "team": 24, "text": 20, "institution": 26, "context": 24,
              "practice": 24, "ethic": 28, "era": 20, "disease": 28}.get(kind, 20),
    )

def E(a, b, rel, note=""):
    EDGES.append(dict(Source=a, Target=b, Relation=rel, Label=note, Type="directed"))

def star(hub, leaves, rel, note):
    for x in leaves:
        E(hub, x, rel, note)

